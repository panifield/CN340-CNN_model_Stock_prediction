"""
weighting.py — งาน B
====================
น้ำหนักตามความใหม่ของข้อมูล (feedback ข้อ 7)

แนวคิด: ตลาดเปลี่ยน regime ได้ ข้อมูลปี 2016 อาจอธิบายปี 2026 ได้น้อยกว่า
ข้อมูลปี 2025 จึงถ่วงน้ำหนักให้แถวใหม่มีอิทธิพลต่อการเทรนมากกว่าแถวเก่า

เลือกวิธี "ถ่วงน้ำหนักครั้งเดียว" ไม่ใช่ "pre-train แล้ว fine-tune"
เพราะแบบหลังเพิ่ม hyperparameter (จำนวนรอบของ stage 2) และเสี่ยงให้โมเดล
ลืมข้อมูลเก่าไปเลย ซึ่งควบคุมและอธิบายยากกว่า

*** น้ำหนักคำนวณจากลำดับเวลาเท่านั้น ไม่ได้ใช้ค่า y -> ไม่มีทาง leak ***
"""

import numpy as np


def recency_weights(n, half_life=None):
    """
    w[i] = 0.5 ** (age_i / half_life)   แล้ว normalize ให้ mean(w) = 1
      age นับเป็น "จำนวนแถว" (= วันทำการ) จากแถวใหม่สุด
      แถวใหม่สุดได้น้ำหนักมากสุด · ถอยไป half_life แถว น้ำหนักเหลือครึ่งของแถวใหม่สุด

    ทำไมต้อง normalize: ถ้าไม่ทำ half-life สั้นจะทำให้ "ผลรวมน้ำหนัก" เล็กลงมาก
    ซึ่งไปเปลี่ยนความแรงของ regularization ด้วย (วัดที่ 1,688 แถว):
        half_life  1000 -> ผลรวม ~995   -> L2 ของ ANN แรงขึ้นราว 1.7 เท่า
        half_life   125 -> ผลรวม ~181   -> L2 ของ ANN แรงขึ้นราว 9.3 เท่า
    (MLPRegressor หาร penalty ด้วยผลรวมน้ำหนัก · XGBoost เทียบ reg_lambda
     และ min_child_weight กับผลรวม hessian ที่ถ่วงน้ำหนักแล้ว)
    stage 1 จะกลายเป็นจูน recency กับ regularization พร้อมกันโดยไม่ตั้งใจ
    normalize แล้ว ผลรวมน้ำหนัก = จำนวนแถวเสมอ -> เปลี่ยนแค่ "สัดส่วน" ระหว่างแถว

    นับเป็นจำนวนแถวไม่ใช่จำนวนวันปฏิทิน เพราะข้อมูลมีเฉพาะวันทำการ
    การนับเป็นวันปฏิทินจะทำให้ช่วงวันหยุดยาวถูกลดน้ำหนักเกินจริง

    half_life=None -> คืน None ซึ่งหมายถึง "ไม่ถ่วงน้ำหนัก"
    """
    if half_life is None:
        return None
    if half_life <= 0:
        raise ValueError(f"half_life ต้องเป็นจำนวนบวก (ได้ {half_life})")
    age = np.arange(n - 1, -1, -1, dtype=float)
    w = 0.5 ** (age / float(half_life))
    return w / w.mean()
